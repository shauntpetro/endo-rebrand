import { spawn } from "node:child_process";
import {
  access,
  cp,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const routeSource = path.join(projectRoot, "tools", "concept-lab", "routes");
const routeTarget = path.join(projectRoot, "app", "concepts");
const markerPath = path.join(routeTarget, ".generated-by-dev-concepts");
const nextBin = path.join(
  projectRoot,
  "node_modules",
  "next",
  "dist",
  "bin",
  "next",
);
const signalExitCodes = {
  SIGHUP: 129,
  SIGINT: 130,
  SIGTERM: 143,
};

async function pathExists(target) {
  try {
    await access(target);
    return true;
  } catch {
    return false;
  }
}

async function prepareRoutes() {
  if (!(await pathExists(routeSource))) {
    throw new Error(`Concept route templates were not found at ${routeSource}`);
  }

  if (await pathExists(routeTarget)) {
    const isGenerated = await pathExists(markerPath);
    const entries = await readdir(routeTarget);

    if (!isGenerated && entries.length > 0) {
      throw new Error(
        "app/concepts contains files that were not generated by dev:concepts; refusing to overwrite them.",
      );
    }

    await rm(routeTarget, { recursive: true, force: true });
  }

  await cp(routeSource, routeTarget, {
    recursive: true,
    errorOnExist: true,
    force: false,
  });
  await writeFile(
    markerPath,
    "Generated by npm run dev:concepts. Do not commit this directory.\n",
    "utf8",
  );
}

async function cleanupRoutes() {
  if (!(await pathExists(markerPath))) return;

  const marker = await readFile(markerPath, "utf8");
  if (!marker.startsWith("Generated by npm run dev:concepts")) return;

  await rm(routeTarget, { recursive: true, force: true });
}

let child;
let requestedSignal;
const signalHandlers = new Map();

const forwardSignal = (signal) => {
  requestedSignal = signal;
  if (child?.exitCode === null) child.kill(signal);
};

try {
  await prepareRoutes();

  child = spawn(
    process.execPath,
    [nextBin, "dev", ...process.argv.slice(2)],
    {
      cwd: projectRoot,
      env: process.env,
      stdio: "inherit",
    },
  );

  for (const signal of Object.keys(signalExitCodes)) {
    const handler = () => forwardSignal(signal);
    signalHandlers.set(signal, handler);
    process.on(signal, handler);
  }

  const result = await new Promise((resolve, reject) => {
    child.once("error", reject);
    child.once("exit", (code, signal) => resolve({ code, signal }));
  });

  process.exitCode =
    result.code ??
    signalExitCodes[result.signal ?? requestedSignal] ??
    1;
} catch (error) {
  console.error(
    `[concept-lab] ${error instanceof Error ? error.message : String(error)}`,
  );
  process.exitCode = 1;
} finally {
  for (const [signal, handler] of signalHandlers) {
    process.off(signal, handler);
  }

  try {
    await cleanupRoutes();
  } catch (error) {
    console.error(
      `[concept-lab] Failed to clean generated routes: ${
        error instanceof Error ? error.message : String(error)
      }`,
    );
    process.exitCode = 1;
  }
}
